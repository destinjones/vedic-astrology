import type { ChartInterpretation, Reading } from '../src';

/** Renders a whole interpretation as Markdown, so a snapshot diff reads like a copy edit. */
export function renderReading(title: string, r: ChartInterpretation): string {
  const out: string[] = [`# ${title}`, '', 'Generated by test/reading-snapshots.test.ts. Do not edit: run `npx vitest run -u` in packages/interpretations after an intended change and review the diff.', ''];
  const reading = (x: Reading, depth = 3) => {
    out.push(`${'#'.repeat(depth)} ${x.title}`, '', `\`${x.id}\` · ${x.tone} · score ${+x.score.toFixed(2)}`, '', `**${x.summary}**`, '');
    for (const d of x.detail) out.push(d, '');
    if (x.strengths.length) out.push(`- Strengths: ${x.strengths.join('; ')}`);
    if (x.challenges.length) out.push(`- Challenges: ${x.challenges.join('; ')}`);
    if (x.remedies?.length) out.push(`- Remedies: ${x.remedies.join('; ')}`);
    out.push('');
  };
  out.push('## Planets', '');
  for (const p of Object.values(r.planets)) {
    out.push(`### ${p.planet}: ${p.dignity} · ${p.tone} · score ${+p.score.toFixed(2)}`, '');
    for (const x of [p.sign, p.house, p.nakshatra, ...p.lordships]) reading(x, 4);
    if (p.retrograde) reading(p.retrograde, 4);
    if (p.combust) out.push(`#### Combust`, '', p.combust, '');
    for (const x of [...p.conjunctions, ...p.aspects]) reading(x, 4);
  }
  out.push('## Yogas', '');
  for (const y of r.yogas) {
    out.push(`### ${y.name} (${y.strength})`, '', `Why: ${y.reason}`, '');
    reading(y.reading, 4);
  }
  out.push('## Doshas', '');
  for (const d of r.doshas) {
    out.push(`### ${d.name}: ${d.present ? d.severity : 'not present'}`, '', `Why: ${d.reason}`, '');
    if (d.cancellations.length) out.push(...d.cancellations.map((c) => `- Cancellation: ${c}`), '');
    if (d.present) reading(d.reading, 4);
  }
  out.push('## Highlights', '', ...r.highlights.strengths.map((x) => `- Strength: ${x.title}`), ...r.highlights.challenges.map((x) => `- Challenge: ${x.title}`), '');
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

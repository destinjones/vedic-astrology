/**
 * Writes content/COVERAGE.md: which readings are written, which are composed, how far
 * each language has got, and the audit state of every yoga.
 *
 *   npx tsx scripts/coverage-report.ts           rewrite the report
 *   npx tsx scripts/coverage-report.ts --check   CI: fail if the committed report is stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LOCALES } from '@vedic/i18n';
import { CONJUNCTIONS, DOSHA_DEFINITIONS, HOUSE_LORD_IN, NAKSHATRAS, PLANETS, PLANET_IN_NAKSHATRA_TEXT, YOGA_DEFINITIONS, YOGA_META, type ContentPack } from '../src';
import hi from '../src/locales/hi';
import { englishCorpus } from '../src/qa/corpus';
import { AVERAGE_GRADE_LIMIT, readability } from '../src/qa/readability';
import FIXTURES from '../test/fixtures/yoga-charts.json';

const root = fileURLToPath(new URL('../', import.meta.url));
const outFile = `${root}content/COVERAGE.md`;
const PACKS: Record<string, ContentPack> = { hi };

const count2d = (x: unknown[][] | undefined) => (x ?? []).reduce((n, row) => n + (row ?? []).filter(Boolean).length, 0);
const countByPlanet = (x: Partial<Record<string, unknown[]>> | undefined) => Object.values(x ?? {}).reduce((n, row) => n + (row ?? []).filter(Boolean).length, 0);
const pct = (n: number, d: number) => `${n}/${d}${n === d ? ' ✓' : n === 0 ? '' : ` (${Math.round((n / d) * 100)}%)`}`;

const writtenNak = PLANETS.reduce((n, p) => n + Object.keys(PLANET_IN_NAKSHATRA_TEXT[p] ?? {}).length, 0);
const yogaIds = Object.keys(YOGA_DEFINITIONS);
const doshaIds = Object.keys(DOSHA_DEFINITIONS);

const rows: [string, number, (pack: ContentPack | undefined, en: boolean) => number][] = [
  ['Planet in sign', 108, (p, en) => (en ? 108 : countByPlanet(p?.planetInSign))],
  ['Planet in house', 108, (p, en) => (en ? 108 : countByPlanet(p?.planetInHouse))],
  ['Planet in nakshatra, hand-written', 243, (_p, en) => (en ? writtenNak : 0)],
  ['House lords', 144, (p, en) => (en ? count2d(HOUSE_LORD_IN) : count2d(p?.houseLords))],
  ['Conjunctions', 35, (p, en) => (en ? Object.keys(CONJUNCTIONS).length : Object.keys(p?.conjunctions ?? {}).length)],
  ['Nakshatra profiles', 27, (p, en) => (en ? NAKSHATRAS.length : (p?.nakshatras ?? []).filter(Boolean).length)],
  ['Yogas', yogaIds.length, (p, en) => (en ? yogaIds.length : yogaIds.filter((id) => p?.yogas?.[id]).length)],
  ['Doshas', doshaIds.length, (p, en) => (en ? doshaIds.length : doshaIds.filter((id) => p?.doshas?.[id]).length)],
];

const md: string[] = [
  '# Reading coverage',
  '',
  'Generated by `scripts/coverage-report.ts`. Do not edit by hand: run `npm run content -w @vedic/interpretations`. CI fails if this file is stale.',
  '',
  'Want to help? Pick an empty cell below and see [CONTRIBUTING.md](../../../CONTRIBUTING.md) and [STYLE.md](STYLE.md).',
  '',
  '## By language',
  '',
  `| Table | ${LOCALES.map((l) => `${l.english}`).join(' | ')} |`,
  `|---|${LOCALES.map(() => '---').join('|')}|`,
  ...rows.map(([name, total, f]) => `| ${name} | ${LOCALES.map((l) => pct(f(PACKS[l.code], l.code === 'en'), total)).join(' | ')} |`),
  '',
  'Languages with no pack fall back to English for every reading. The interface itself is translated separately, in `apps/web/src/i18n/messages`.',
  '',
  '## Planet in nakshatra',
  '',
  `${writtenNak} of 243 cells have a hand-written reading (✍). The rest (·) are composed from the nakshatra profile, the planet and the relationship between the planet and the nakshatra lord, which reads well but generically. Writing one is the best first contribution: add it to \`content/planet-in-nakshatra/<planet>.yaml\`.`,
  '',
  `| Nakshatra | ${PLANETS.map((p) => p[0].toUpperCase() + p.slice(1)).join(' | ')} |`,
  `|---|${PLANETS.map(() => ':-:').join('|')}|`,
  ...NAKSHATRAS.map((n) => `| ${n.number}. ${n.name} | ${PLANETS.map((p) => (PLANET_IN_NAKSHATRA_TEXT[p]?.[n.number] ? '✍' : '·')).join(' | ')} |`),
  '',
  '## Yoga audit',
  '',
  'Every yoga needs a citation, a cancellation note and a positive test chart, or CI fails (`test/yoga-lint.test.ts`). A citation is *verified* once someone has checked it against a printed translation and named the edition in `content/yogas.yaml`.',
  '',
  `Verified citations: ${pct(yogaIds.filter((id) => YOGA_META[id]?.citation.verified).length, yogaIds.length)}`,
  '',
  '| Yoga | Source | Verified | Test chart | Cancellation note |',
  '|---|---|:-:|:-:|:-:|',
  ...yogaIds.map((id) => {
    const m = YOGA_META[id];
    const src = m ? [m.citation.source, m.citation.ref].filter(Boolean).join(', ') : '**missing**';
    return `| ${YOGA_DEFINITIONS[id].name} | ${src} | ${m?.citation.verified ? '✓' : '·'} | ${(FIXTURES as Record<string, unknown>)[id] ? '✓' : '**missing**'} | ${m?.cancellation ? '✓' : '**missing**'} |`;
  }),
  '',
];

const corpus = englishCorpus().map((c) => ({ ...c, r: readability(c.text) }));
const avg = corpus.reduce((s, c) => s + c.r.grade, 0) / corpus.length;
const hardest = [...corpus].filter((c) => c.r.words >= 30).sort((a, b) => b.r.grade - a.r.grade).slice(0, 10);
md.push(
  '## Readability (English)',
  '',
  `Average Flesch–Kincaid grade over ${corpus.length} readings: **${avg.toFixed(2)}** (CI limit ${AVERAGE_GRADE_LIMIT}). The ten hardest readings, which are the first to simplify:`,
  '',
  '| Reading | Grade | Words | Longest sentence |',
  '|---|--:|--:|--:|',
  ...hardest.map((c) => `| \`${c.id}\` | ${c.r.grade} | ${c.r.words} | ${c.r.longestSentence} |`),
  '',
);

const out = md.join('\n');
if (process.argv.includes('--check')) {
  const cur = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (cur !== out) {
    console.error('content/COVERAGE.md is out of date. Run `npm run content -w @vedic/interpretations` and commit the result.');
    process.exit(1);
  }
  console.log('coverage: OK');
} else {
  writeFileSync(outFile, out);
  console.log('coverage: wrote content/COVERAGE.md');
}

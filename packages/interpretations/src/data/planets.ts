import type { PlanetId, SignNumber } from '../types';

export interface PlanetProfile {
  id: PlanetId;
  name: string;
  sanskrit: string;
  glyph: string;
  /** Natural benefic or malefic. Mercury and Moon vary by condition. */
  nature: 'benefic' | 'malefic' | 'variable';
  element: string;
  gender: 'male' | 'female' | 'neutral';
  /** What the planet signifies (karakatva). */
  significations: string[];
  /** Body areas traditionally linked to the planet. */
  body: string[];
  /** Short essence used when composing combined readings. */
  essence: string;
  /** How the planet behaves when well placed. */
  highExpression: string;
  /** How the planet behaves when afflicted. */
  lowExpression: string;
  ownSigns: SignNumber[];
  exaltation: { sign: SignNumber; degree: number } | null;
  debilitation: { sign: SignNumber; degree: number } | null;
  moolatrikona: { sign: SignNumber; from: number; to: number } | null;
  friends: PlanetId[];
  neutrals: PlanetId[];
  enemies: PlanetId[];
  /** Houses counted from the planet that receive its full aspect (7 is universal). */
  aspects: number[];
  /** Vimshottari mahadasha length in years. */
  dashaYears: number;
  /** Degrees within which the planet is considered combust by the Sun. */
  combustOrb: number | null;
  color: string;
  gemstone: string;
  day: string;
  mantra: string;
}

